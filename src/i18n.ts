const DICTS: Record<Lang, Dict> = { pt: PT, en: EN, es: ES, ru: RU };

export type TKey = keyof Dict;

export function tr(
  lang: Lang,
  key: TKey,
  vars?: Record<string, string | number>
): string {
  let s = DICTS[lang]?.[key] ?? PT[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replace(`{${k}}`, String(v));
    }
  }
  return s;
}
